from collections import deque

def bfs(grid, start):
    rows = len(grid)
    cols = len(grid[0])
    q = deque([start])
    visited = {start}
    while q:
        x, y = q.popleft()
        if grid[y][x] == 2:
            return True
        for dx, dy in [(0, 1), (0, -1), (1, 0), (-1, 0)]:
            nx, ny = x + dx, y + dy
            if 0 <= nx < cols and 0 <= ny < rows:
                if (nx, ny) not in visited and grid[ny][nx] in [1, 2]:
                    visited.add((nx, ny))
                    q.append((nx, ny))
    return False

def check_stage(stage_idx, stage):
    grid = stage['grid']
    start = stage['start']
    # Check size
    if len(grid) != 6 or any(len(row) != 6 for row in grid):
        return False, f"Stage {stage_idx}: Not 6x6"
    # Check start on 1 or 2
    if grid[start['y']][start['x']] not in [1, 2]:
        val = grid[start['y']][start['x']]
        return False, f"Stage {stage_idx}: Start ({start['x']},{start['y']}) not on path (Value: {val})"
    # Check connectivity
    if not bfs(grid, (start['x'], start['y'])):
        return False, f"Stage {stage_idx}: Destination not reachable"
    return True, f"Stage {stage_idx}: OK"

